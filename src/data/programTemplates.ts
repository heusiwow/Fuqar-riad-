const EXERCISE_BY_ID = new Map(BUILTIN_EXERCISES.map((ex) => [ex.id, ex]));

function exItem(
  exerciseId: string,
  sets: number,
  targetRepsMin: number,
  targetRepsMax: number,
  opts: {
    warmupSets?: number;
    targetRpe?: number;
    targetRir?: number;
    restSeconds?: number;
    technique?: WorkoutExerciseItem['technique'];
    supersetGroup?: string;
    notes?: string;
  } = {}
): Omit<WorkoutExerciseItem, 'itemId'> {
  const found = EXERCISE_BY_ID.get(exerciseId) || BUILTIN_EXERCISES[0];
  return {
    exerciseId: found.id,
    exerciseNameEn: found.nameEn,
    exerciseNameAr: found.nameAr,
    sets,
    warmupSets: opts.warmupSets ?? 0,
    targetRepsMin,
    targetRepsMax,
    targetRpe: opts.targetRpe,
    targetRir: opts.targetRir,
    restSeconds: opts.restSeconds ?? 90,
    technique: opts.technique ?? 'standard',
    supersetGroup: opts.supersetGroup,
    notes: opts.notes ?? '',
  };
}

