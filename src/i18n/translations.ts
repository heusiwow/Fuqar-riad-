export function tLabel(item: { en: string; ar: string }, lang: Language): string {
  return lang === 'ar' ? item.ar : item.en;
}

export function formatArabicCount(
  count: number,
  singular: string,
  dual: string,
  plural: string,
  accusativeSingular?: string
): string {
  const n = Math.abs(Math.floor(count));
  if (n === 0) return `0 ${plural}`;
  if (n === 1) return singular;
  if (n === 2) return dual;
  const mod100 = n % 100;
  if (mod100 >= 3 && mod100 <= 10) return `${n} ${plural}`;
  return `${n} ${accusativeSingular || singular}`;
}
